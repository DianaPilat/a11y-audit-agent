"""WCAG 2.1 A/AA success criteria with embedding retrieval, and the in-process `lookup_wcag` tool.

`WcagIndex` embeds every success criterion once with a local sentence-transformers model
and ranks them by cosine similarity to a free-text query (an axe rule's help text, or the
auditor's description of an issue). `build_wcag_server` exposes it to the Agent SDK as an
in-process MCP server.
"""

import json
from collections.abc import Callable
from functools import lru_cache
from pathlib import Path
from typing import Any

import numpy as np
from claude_agent_sdk import SdkMcpTool, create_sdk_mcp_server, tool

DATA_DIR = Path(__file__).resolve().parent / "data"
DATA_PATH = DATA_DIR / "wcag21.json"  # generated by scripts/build_wcag_data.py
FAILURES_PATH = DATA_DIR / "wcag21_failures.json"  # hand-written: typical failures per criterion
EMBEDDING_MODEL = "sentence-transformers/all-MiniLM-L6-v2"
DEFAULT_LIMIT = 3
MAX_LIMIT = 5

SERVER_NAME = "wcag"
LOOKUP_WCAG_TOOL = f"mcp__{SERVER_NAME}__lookup_wcag"

Embedder = Callable[[list[str]], np.ndarray]


@lru_cache(maxsize=1)
def load_criteria() -> dict[str, dict[str, Any]]:
    """WCAG 2.1 level A and AA success criteria, keyed by number (e.g. '1.4.3')."""
    failures = json.loads(FAILURES_PATH.read_text(encoding="utf-8"))
    return {c["num"]: {**c, "failures": failures[c["num"]]} for c in json.loads(DATA_PATH.read_text(encoding="utf-8"))}


def is_known_criterion(num: str) -> bool:
    return num in load_criteria()


@lru_cache(maxsize=1)
def _default_embedder() -> Embedder:
    from sentence_transformers import SentenceTransformer  # heavy import: only when first needed

    model = SentenceTransformer(EMBEDDING_MODEL)
    return lambda texts: model.encode(texts, normalize_embeddings=True, show_progress_bar=False)


def _document(criterion: dict[str, Any]) -> str:
    """The text embedded for a criterion: its name, normative sentence and typical failures.

    The normative wording is abstract ("name, role, value"), so the failures give it the
    vocabulary people use to describe real issues ("button has no accessible name").
    """
    return f"{criterion['name']}. {criterion['text']} Typical failures: {criterion['failures']}."


def _match(criterion: dict[str, Any], score: float) -> dict[str, Any]:
    """The compact form returned to the agent."""
    return {
        "criterion": criterion["num"],
        "name": criterion["name"],
        "level": criterion["level"],
        "requirement": criterion["text"],
        "url": criterion["url"],
        "score": round(score, 3),
    }


class WcagIndex:
    def __init__(self, embedder: Embedder | None = None) -> None:
        self._embed = embedder or _default_embedder()
        self._criteria = list(load_criteria().values())
        self._vectors = self._embed([_document(c) for c in self._criteria])

    def search(self, query: str, limit: int = DEFAULT_LIMIT) -> list[dict[str, Any]]:
        """The `limit` criteria closest to the query, best first, each with a 0-1 similarity score."""
        limit = max(1, min(limit, MAX_LIMIT))
        scores = self._vectors @ self._embed([query])[0]
        best = np.argsort(-scores)[:limit]
        return [_match(self._criteria[i], float(scores[i])) for i in best]


@lru_cache(maxsize=1)
def default_index() -> WcagIndex:
    return WcagIndex()


def _reply(payload: dict[str, Any], *, is_error: bool = False) -> dict[str, Any]:
    result: dict[str, Any] = {"content": [{"type": "text", "text": json.dumps(payload)}]}
    if is_error:
        result["is_error"] = True
    return result


def make_lookup_wcag_tool(index: WcagIndex | None = None) -> SdkMcpTool:
    @tool(
        "lookup_wcag",
        "Find the WCAG 2.1 success criteria that best match an accessibility issue. Describe the "
        "issue in a sentence (e.g. 'form input has no label', 'text has insufficient color contrast'). "
        "Returns the closest criteria, best first, with number, level and official wording. Pick the "
        "one whose wording the issue actually violates; use its number as the finding's wcag_criterion.",
        {"query": str, "limit": int},
    )
    async def lookup_wcag(args: dict[str, Any]) -> dict[str, Any]:
        query = str(args.get("query", "")).strip()
        if not query:
            return _reply({"error": "query must not be empty"}, is_error=True)
        results = (index or default_index()).search(query, int(args.get("limit") or DEFAULT_LIMIT))
        return _reply({"matches": results})

    return lookup_wcag


def build_wcag_server(index: WcagIndex | None = None):
    return create_sdk_mcp_server(SERVER_NAME, tools=[make_lookup_wcag_tool(index)])
